// ================================================================
// 模块名：tb_hdmi
// 功能：hdmi_timing + pattern_gen 的测试平台
// 说明：跳过 PLL 和 LVDS，直接仿真核心逻辑
// ================================================================

`timescale 1ns / 1ps

module tb_hdmi();

// ================================================================
// 1. 信号定义
// ================================================================
// 输入
reg         clk;                // 像素时钟（25MHz）
reg         rst_n;              // 复位（低有效）
reg  [1:0]  pattern_sel;        // 图案选择

// 输出（hdmi_timing）
wire [11:0] pix_x;
wire [11:0] pix_y;
wire        pix_de;
wire        pix_hs;
wire        pix_vs;

// 输出（pattern_gen）
wire [15:0] pattern_rgb;

// ================================================================
// 2. 时钟生成（25MHz，周期 40ns）
// ================================================================
initial clk = 1'b0;
always #20 clk = ~clk;    // 每 20ns 翻转一次 → 40ns 周期 → 25MHz

// ================================================================
// 3. 例化 hdmi_timing
// ================================================================
hdmi_timing u_timing (
    .pix_clk (clk),
    .rst_n   (rst_n),
    .pix_x   (pix_x),
    .pix_y   (pix_y),
    .pix_de  (pix_de),
    .pix_hs  (pix_hs),
    .pix_vs  (pix_vs)
);

// ================================================================
// 4. 例化 pattern_gen
// ================================================================
pattern_gen u_pattern (
    .pix_clk     (clk),
    .rst_n       (rst_n),
    .pix_x       (pix_x[9:0]),
    .pix_y       (pix_y[9:0]),
    .pix_de      (pix_de),
    .pattern_sel (pattern_sel),
    .pattern_rgb (pattern_rgb)
);

// ================================================================
// 5. 测试激励
// ================================================================
initial begin
    // ---- 初始化 ----
    rst_n       = 1'b0;
    pattern_sel = 2'b00;    // 彩条模式
    
    // ---- 复位保持 100ns ----
    #100;
    rst_n = 1'b1;
    
    // ---- 测试彩条（跑 1 帧）----
    // 一帧 = 800 × 525 × 40ns = 16.8ms
    #16800000;
    
    // ---- 切换到网格 ----
    pattern_sel = 2'b01;
    #16800000;
    
    // ---- 切换到矩形 ----
    pattern_sel = 2'b10;
    #16800000;
    
    // ---- 切换到字符 ----
    pattern_sel = 2'b11;
    #16800000;
    
    // ---- 结束 ----
    $display("Simulation finished at time %t", $time);
    $stop;
end

// ================================================================
// 6. 生成波形文件（可选）
// ================================================================
initial begin
    $dumpfile("tb_hdmi.vcd");
    $dumpvars(0, tb_hdmi);
end

endmodule